export function suggestDiseases(complaint: string, complaintCode: string): string[] {
  const text = (complaint + " " + complaintCode).toLowerCase();
  const matched = new Set<string>();
  for (const entry of complaintDiseaseMap) {
    if (entry.keywords.some((kw) => text.includes(kw.toLowerCase()))) {
      matched.add(entry.diseaseId);
    }
  }
  return Array.from(matched);
}

